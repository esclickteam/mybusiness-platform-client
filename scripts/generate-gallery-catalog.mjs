#!/usr/bin/env node
/**
 * Builds a lightweight gallery catalog from template meta files without
 * importing pages/preview/defaultData. WebsiteTemplatesPage must not import
 * the studio template barrel — that pulls ~200 renderers into the gallery chunk.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const templatesDir = path.resolve(
  __dirname,
  "../src/components/site-builder/studio/data/templates",
);
const indexPath = path.join(templatesDir, "index.ts");
const outPath = path.join(templatesDir, "galleryCatalog.ts");

function extractQuoted(source, field) {
  const re = new RegExp(
    `(?:^|\\n)\\s*${field}:\\s*(?:\\n\\s*)?(["'\`])([\\s\\S]*?)\\1`,
  );
  const match = source.match(re);
  if (!match) return "";
  return match[2]
    .replace(/\\n/g, "\n")
    .replace(/\\"/g, '"')
    .replace(/\\'/g, "'")
    .replace(/\\\\/g, "\\")
    .trim();
}

function templateBlock(source) {
  const start = source.search(
    /export\s+const\s+\w+Template\b[\s\S]{0,80}?=/,
  );
  if (start < 0) return source;
  const fromAssign = source.slice(start);
  const brace = fromAssign.indexOf("{");
  if (brace < 0) return fromAssign;
  return fromAssign.slice(brace);
}

function parseMetaFile(filePath) {
  const source = fs.readFileSync(filePath, "utf8");
  const block = templateBlock(source);
  const id =
    extractQuoted(block, "id") ||
    extractQuoted(block, "key") ||
    extractQuoted(block, "templateId");
  if (!id) return null;
  return {
    id,
    name: extractQuoted(block, "name") || id,
    category: extractQuoted(block, "category") || "business",
    categoryLabel: extractQuoted(block, "categoryLabel"),
    badge: extractQuoted(block, "badge"),
    description: extractQuoted(block, "description"),
  };
}

function listMetaFiles() {
  return fs
    .readdirSync(templatesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .flatMap((entry) => {
      const ts = path.join(templatesDir, entry.name, "meta.ts");
      const tsx = path.join(templatesDir, entry.name, "meta.tsx");
      if (fs.existsSync(ts)) return [{ folder: entry.name, file: ts }];
      if (fs.existsSync(tsx)) return [{ folder: entry.name, file: tsx }];
      return [];
    });
}

function indexOrder() {
  const source = fs.readFileSync(indexPath, "utf8");
  const imports = new Map();
  const importRe =
    /import\s+\{\s*(?:(\w+)\s+as\s+)?(\w+)\s*\}\s+from\s+["']\.\/([^"']+)\/meta["']/g;
  let match;
  while ((match = importRe.exec(source))) {
    const exportedName = match[2];
    const folder = match[3];
    imports.set(exportedName, folder);
  }

  const arrayMatch = source.match(
    /export const studioTemplateDefinitions[\s\S]*?=\s*\[([\s\S]*?)\];/,
  );
  if (!arrayMatch) return [];
  return [...arrayMatch[1].matchAll(/^\s*(\w+)\s*,?\s*$/gm)]
    .map((item) => imports.get(item[1]))
    .filter(Boolean);
}

function tsString(value) {
  return JSON.stringify(value ?? "");
}

const metas = listMetaFiles();
const byFolder = new Map();
for (const entry of metas) {
  const parsed = parseMetaFile(entry.file);
  if (!parsed) {
    console.warn(`skip meta without id: ${entry.folder}`);
    continue;
  }
  byFolder.set(entry.folder, parsed);
}

const seen = new Set();
const ordered = [];
for (const folder of indexOrder()) {
  const parsed = byFolder.get(folder);
  if (!parsed || seen.has(parsed.id.toLowerCase())) continue;
  seen.add(parsed.id.toLowerCase());
  ordered.push(parsed);
}

for (const parsed of byFolder.values()) {
  if (seen.has(parsed.id.toLowerCase())) continue;
  seen.add(parsed.id.toLowerCase());
  ordered.push(parsed);
}

const body = ordered
  .map(
    (entry) =>
      `  { id: ${tsString(entry.id)}, name: ${tsString(entry.name)}, category: ${tsString(entry.category)}, categoryLabel: ${tsString(entry.categoryLabel)}, badge: ${tsString(entry.badge)}, description: ${tsString(entry.description)} },`,
  )
  .join("\n");

const file = `/* eslint-disable */
/* Generated by scripts/generate-gallery-catalog.mjs — do not edit by hand. */

export type StudioGalleryCatalogEntry = {
  id: string;
  name: string;
  category: string;
  categoryLabel: string;
  badge: string;
  description: string;
};

export const studioGalleryCatalog: StudioGalleryCatalogEntry[] = [
${body}
];

export function getStudioGalleryCatalog(): StudioGalleryCatalogEntry[] {
  return studioGalleryCatalog;
}

export function getStudioGalleryCatalogEntry(
  templateId: string | null | undefined,
): StudioGalleryCatalogEntry | undefined {
  const key = String(templateId || "").trim().toLowerCase();
  if (!key) return undefined;
  return studioGalleryCatalog.find((entry) => entry.id.toLowerCase() === key);
}
`;

fs.writeFileSync(outPath, file);
console.log(`Wrote ${ordered.length} gallery catalog entries to ${outPath}`);
