export function withMetaCostCopy<T extends { whatsapp?: { nav?: Record<string, string> } }>(
  translation: T,
  code: string
): T {
  const extra = copy[code] || copy.en;
  const whatsapp = translation.whatsapp || {};
  return {
    ...translation,
    whatsapp: {
      ...whatsapp,
      nav: { ...(whatsapp.nav || {}), metaCosts: extra.nav },
      metaCosts: extra.metaCosts,
    },
  };
}
