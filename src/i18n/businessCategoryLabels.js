const LOCALE_INDEX = { he: 0, en: 2, es: 3, "pt-BR": 4, ar: 5 };

export const BUSINESS_CATEGORY_SLUGS = Object.fromEntries(
  BUSINESS_CATEGORY_ROWS.map(([he, slug]) => [he, slug])
);

export function businessCategoryKey(name) {
  const slug = BUSINESS_CATEGORY_SLUGS[String(name || "").trim()];
  return slug ? `business.categoryNames.${slug}` : null;
}

export function translateBusinessCategory(name, t) {
  const clean = String(name || "").trim();
  if (!clean) return "";
  const key = businessCategoryKey(clean);
  if (!key || !t) return clean;
  return t(key, { defaultValue: clean });
}

export function categoryNamesCatalog(locale) {
  const index = LOCALE_INDEX[locale] ?? LOCALE_INDEX.en;
  return Object.fromEntries(
    BUSINESS_CATEGORY_ROWS.map((row) => [row[1], row[index] || row[2]])
  );
}
