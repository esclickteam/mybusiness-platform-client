export function getCrmLeadGuide(slug, locale) {
  if (slug !== "crm-lead-management") return null;
  const article = getCrmLeadArticle(locale);
  const sections = [];
  for (const section of article.sections) {
    sections.push({
      id: section.id,
      heading: section.heading,
      paragraphs: section.paragraphs || [],
      steps: section.steps,
      table: section.table,
      shots: (section.shots || []).map((shot) => ({
        src: `/guides/crm-lead-management/${shot.file}`,
        alt: shot.alt,
        caption: `${shot.title}. ${shot.caption}`,
      })),
      films: (section.films || []).map((film) => ({
        src: `/guides/crm-lead-management/${film.file}`,
        poster: `/guides/crm-lead-management/${film.poster}`,
        title: film.title,
        caption: film.caption,
        transcript: film.transcript,
        file: film.file,
      })),
    });
    for (const sub of section.subsections || []) {
      sections.push({ id: sub.id, level: 3, heading: sub.heading, paragraphs: sub.paragraphs || [] });
    }
  }
  return {
    title: article.title,
    description: article.description,
    h1: article.h1,
    lede: article.dek,
    updated: "2026-10-29",
    published: "2026-10-29",
    faq: article.faq,
    sections,
    image: "https://bizuply.com/guides/crm-lead-management/leads-workspace.webp",
    videos: videosFor(article),
  };
}

