function isoDuration(seconds) {
  const total = Math.round(seconds);
  const minutes = Math.floor(total / 60);
  const secs = total % 60;
  return minutes ? `PT${minutes}M${secs}S` : `PT${secs}S`;
}

function videosFor(article) {
  const videos = [];
  for (const section of article.sections) {
    for (const film of section.films || []) {
      videos.push({
        name: film.title,
        description: film.caption,
        thumbnailUrl: `https://bizuply.com/guides/crm-lead-management/${film.poster}`,
        uploadDate: "2026-10-29",
        duration: isoDuration(VIDEO_SECONDS[film.file]),
        contentUrl: `https://bizuply.com/guides/crm-lead-management/${film.file}`,
      });
    }
  }
  return videos;
}
