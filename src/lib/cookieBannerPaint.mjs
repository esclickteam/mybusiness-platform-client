function escapeText(value) {
  return String(value || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

export function cookieCopy(locale) {
  return COOKIE_BANNER_COPY[locale] || COOKIE_BANNER_COPY.en;
}

export function trackingChoiceFromCookie(cookieHeader = "") {
  const values = String(cookieHeader)
    .split(";")
    .map((part) => part.trim())
    .filter((part) => part.startsWith("bizuply_tracking="))
    .map((part) => {
      const raw = part.slice("bizuply_tracking=".length);
      try {
        return decodeURIComponent(raw);
      } catch {
        return raw;
      }
    });
  const value = values.length ? values[values.length - 1] : "";
  if (value === "all" || value.startsWith("v2:ad")) return "all";
  if (value === "essential" || value.startsWith("v2:none")) return "essential";
  return "unknown";
}

function localePaths(locale) {
  const prefix = locale === "pt-BR" ? "/pt-br" : locale && locale !== "en" ? `/${locale}` : "";
  return {
    privacy: `${prefix}/privacy`,
    cookies: `${prefix}/privacy#section-8`,
    terms: `${prefix}/terms`,
  };
}

function legalLinks(copy, locale) {
  const { privacy, cookies, terms } = localePaths(locale);
  return `${escapeText(copy.change)} ${escapeText(copy.more)}<a href="${privacy}">${escapeText(copy.policy)}</a>${escapeText(copy.join)}<a href="${cookies}">${escapeText(copy.cookiePolicy)}</a>${escapeText(copy.termsJoin)}<a href="${terms}">${escapeText(copy.terms)}</a>`;
}

function noticeLinks(copy, locale) {
  const { privacy, cookies } = localePaths(locale);
  return `<a href="${privacy}">${escapeText(copy.policy)}</a><a href="${cookies}">${escapeText(copy.cookiePolicy)}</a>`;
}

function row(copy, name, provider, purpose, duration) {
  return `<tr><td>${escapeText(name)}</td><td>${escapeText(provider)}</td><td>${escapeText(purpose)}</td><td>${escapeText(duration)}</td></tr>`;
}

function category(copy, id, title, detail, control, rows, note) {
  const inner = rows
    ? `<table class="cookie-banner__table"><thead><tr><th>${escapeText(copy.name)}</th><th>${escapeText(copy.provider)}</th><th>${escapeText(copy.purpose)}</th><th>${escapeText(copy.duration)}</th></tr></thead><tbody>${rows}</tbody></table>`
    : `<p class="cookie-banner__note">${escapeText(note || copy.noneFound)}</p>`;
  return `<section class="cookie-banner__cat"><div class="cookie-banner__row"><h3><button type="button" class="cookie-banner__disclose" aria-expanded="false" aria-controls="${id}" onclick="window.bizuplyToggleCookieDetails(this)"><span class="cookie-banner__chevron" aria-hidden="true"></span>${escapeText(title)}</button></h3>${control}</div><p>${escapeText(detail)}</p><div class="cookie-banner__details" id="${id}" hidden>${inner}</div></section>`;
}

export function renderCookieNoticeInner(locale) {
  const copy = cookieCopy(locale);
  return `<div class="cookie-banner__scroll"><h2 id="bizuply-cookie-paint-title" class="cookie-banner__sr">${escapeText(copy.noticeTitle)}</h2><p class="cookie-banner__message">${escapeText(copy.noticeIntro)}</p><p class="cookie-banner__links">${noticeLinks(copy, locale)}</p></div><div class="cookie-banner__actions"><button type="button" class="cookie-banner__primary" onclick="window.bizuplyChooseCookies('all')">${escapeText(copy.acceptAll)}</button><button type="button" class="cookie-banner__outline" onclick="window.bizuplyChooseCookies('essential')">${escapeText(copy.essentialOnly)}</button><button type="button" class="cookie-banner__secondary" onclick="window.bizuplyOpenCookieManager()">${escapeText(copy.manage)}</button></div>`;
}

