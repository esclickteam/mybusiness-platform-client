export const HX_HERO_LOCALES = HERO;

export function cinematicLocale(language) {
  const value = String(language || "en").toLowerCase();
  if (value.startsWith("pt")) return "pt-BR";
  if (value.startsWith("he")) return "he";
  if (value.startsWith("es")) return "es";
  if (value.startsWith("ar")) return "ar";
  return "en";
}

export function cinematicFor(language) {
  const locale = cinematicLocale(language);
  return { hero: HERO[locale], ...REST[locale] };
}
