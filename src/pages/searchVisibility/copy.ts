export function svCopy(language: string) {
  return copy[svLocale(language)];
}

export function pick(row: Record<string, string> | undefined, language: string, heKey: string, enKey: string) {
  if (!row) return "";
  return svLocale(language) === "he" ? row[heKey] || row[enKey] || "" : row[enKey] || row[heKey] || "";
}
